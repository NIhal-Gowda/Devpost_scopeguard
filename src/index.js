import api, { route } from '@forge/api';
import { kvs } from '@forge/kvs';
import { fetchActiveSOWConstraints, cleanConfluenceMarkup, FALLBACK_DEMO_SOW } from './sowParser';
import { evaluateIssueDrift } from './driftEngine';

/**
 * 1. Rovo Action Handler: fetch-sow-constraints
 * Invoked by Rovo Agent "ScopeGuard Contract Sentinel".
 * Returns active contractual boundaries from Confluence or Forge KVS.
 */
export async function fetchSowConstraints(event) {
  console.log('[ScopeGuard] Rovo Action: fetchSowConstraints invoked');
  const spaceKey = event?.inputs?.spaceKey || event?.spaceKey || null;

  try {
    const sow = await fetchActiveSOWConstraints(spaceKey);
    return {
      status: 'SUCCESS',
      sowTitle: sow.title,
      sowOwner: sow.owner,
      sowUrl: sow.url,
      effectiveVersion: sow.version,
      excludedClausesCount: sow.clauses.length,
      contractClauses: sow.clauses.map(c => ({
        clauseId: c.id,
        category: c.category,
        title: c.title,
        bindingRule: c.rule,
        exclusionKeywords: c.keywords
      })),
      governanceGuideline:
        'All Jira tickets must strictly adhere to these clauses. Any requested feature matching exclusion keywords constitutes unbilled scope drift and must be converted to a Paid Change Request.'
    };
  } catch (error) {
    console.error('[ScopeGuard] Error in fetchSowConstraints:', error);
    return {
      status: 'FALLBACK_ACTIVE',
      sowTitle: FALLBACK_DEMO_SOW.title,
      contractClauses: FALLBACK_DEMO_SOW.clauses,
      error: error.message
    };
  }
}

/**
 * 2. Rovo Action Handler: convert-to-change-request
 * Invoked by Rovo Agent to convert an out-of-scope Jira ticket into a Paid Change Request.
 */
export async function convertToChangeRequest(event) {
  console.log('[ScopeGuard] Rovo Action: convertToChangeRequest invoked with inputs:', event?.inputs);
  const inputs = event?.inputs || event || {};
  const { issueKey, violatedClause, estimatedImpact } = inputs;

  if (!issueKey) {
    return {
      success: false,
      error: 'Missing required parameter: issueKey (e.g. PROJ-123)'
    };
  }

  const impactText = estimatedImpact || '$7,500 Scope Adjustment / 40 Engineering Hours';
  const clauseText = violatedClause || 'SOW Clause: Prohibited Third-Party Gateway / Platform Exclusion';

  try {
    // 1. Label Jira ticket with 'paid-change-request'
    await api.asApp().requestJira(route`/rest/api/3/issue/${issueKey}`, {
      method: 'PUT',
      headers: {
        'Accept': 'application/json',
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        update: {
          labels: [
            { add: 'paid-change-request' },
            { add: 'scopeguard-flagged' }
          ]
        }
      })
    });

    // 2. Post formal ADF comment to Jira ticket
    const commentBody = {
      body: {
        version: 1,
        type: 'doc',
        content: [
          {
            type: 'heading',
            attrs: { level: 3 },
            content: [
              {
                type: 'text',
                text: '🛡️ ScopeGuard Rovo Agent Scope Breach Notice'
              }
            ]
          },
          {
            type: 'paragraph',
            content: [
              { type: 'text', text: 'Action Taken: ', marks: [{ type: 'strong' }] },
              { type: 'text', text: 'CONVERTED TO PAID CHANGE REQUEST', marks: [{ type: 'code' }] }
            ]
          },
          {
            type: 'paragraph',
            content: [
              { type: 'text', text: 'Breached SOW Clause: ', marks: [{ type: 'strong' }] },
              { type: 'text', text: clauseText, marks: [{ type: 'em' }] }
            ]
          },
          {
            type: 'paragraph',
            content: [
              { type: 'text', text: 'Estimated Financial Impact: ', marks: [{ type: 'strong' }] },
              { type: 'text', text: impactText }
            ]
          },
          {
            type: 'paragraph',
            content: [
              {
                type: 'text',
                text: 'Automated notice generated by ScopeGuard Sentinel in Atlassian Rovo. Delivery team must not begin development until client executes formal commercial change approval.'
              }
            ]
          }
        ]
      }
    };

    await api.asApp().requestJira(route`/rest/api/3/issue/${issueKey}/comment`, {
      method: 'POST',
      headers: {
        'Accept': 'application/json',
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(commentBody)
    });

    // 3. Log event into Forge KVS
    const changeRecord = {
      issueKey,
      status: 'CHANGE_REQUEST_CREATED',
      violatedClause: clauseText,
      estimatedImpact: impactText,
      actionTakenBy: 'Rovo:ScopeGuard Sentinel',
      timestamp: new Date().toISOString()
    };

    await kvs.set(`audit:${issueKey}`, changeRecord);
    await kvs.set(`cr:${issueKey}`, changeRecord);

    return {
      success: true,
      message: `Issue ${issueKey} successfully converted to Paid Change Request. Label 'paid-change-request' applied and legal audit comment posted.`,
      issueKey,
      changeRequestId: `CR-${issueKey}`,
      violatedClause: clauseText,
      estimatedImpact: impactText
    };
  } catch (error) {
    console.error('[ScopeGuard] Failed to convert to change request:', error);
    return {
      success: false,
      error: error.message
    };
  }
}

/**
 * 3. Trigger Handler: avi:jira:created:issue & avi:jira:updated:issue
 * Automatically evaluates tickets in the background and saves audit in Forge KVS.
 */
export async function onIssueEvent(event) {
  const issueKey = event?.issue?.key;
  if (!issueKey) return;

  console.log(`[ScopeGuard Trigger] Auditing Jira Issue ${issueKey}`);
  try {
    const summary = event.issue.fields?.summary || '';
    const description = typeof event.issue.fields?.description === 'string'
      ? event.issue.fields.description
      : JSON.stringify(event.issue.fields?.description || '');

    const sow = await fetchActiveSOWConstraints();
    const audit = await evaluateIssueDrift(`${summary} ${description}`, sow);
    audit.issueKey = issueKey;

    await kvs.set(`audit:${issueKey}`, audit);
    console.log(`[ScopeGuard Trigger] Issue ${issueKey} audited: ${audit.status} (${audit.riskScore}%)`);
  } catch (err) {
    console.error(`[ScopeGuard Trigger] Error auditing issue ${issueKey}:`, err);
  }
}

/**
 * 4. Trigger Handler: avi:confluence:created:page & avi:confluence:updated:page
 * Refreshes SOW index in Forge KVS whenever a Confluence page is updated.
 */
export async function onConfluencePageEvent(event) {
  const pageId = event?.page?.id;
  console.log(`[ScopeGuard Trigger] Confluence page event received for pageId: ${pageId}`);

  try {
    // Re-sync active SOW constraints
    const refreshedSow = await fetchActiveSOWConstraints();
    console.log(`[ScopeGuard Trigger] Synced active SOW: "${refreshedSow.title}" with ${refreshedSow.clauses.length} clauses.`);
  } catch (err) {
    console.error('[ScopeGuard Trigger] Error syncing Confluence page:', err);
  }
}
